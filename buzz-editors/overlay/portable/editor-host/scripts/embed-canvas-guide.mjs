// Embed packages/editor-host/canvas-guide/*.md into src/canvas-guide.ts, so every host (Studio, Buzz, CopyOS) serves the
// same guide without shipping the markdown files. Edit the .md files, then run: node packages/editor-host/scripts/embed-canvas-guide.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const order = ['canvas-use', 'generate-design', 'api-reference', 'gotchas', 'text', 'paints-effects-masks', 'vectors-icons',
  'components-variables-styles', 'validation-and-recovery', 'figma-tools']
const files = readdirSync(join(root, 'canvas-guide')).filter(name => name.endsWith('.md')).map(name => name.slice(0, -3))
for (const name of files) if (!order.includes(name)) order.push(name)
const topics = Object.fromEntries(order.filter(name => files.includes(name)).map(name => [name, readFileSync(join(root, 'canvas-guide', `${name}.md`), 'utf8')]))
const titles = Object.fromEntries(Object.entries(topics).map(([name, text]) => [name, (/^# .*?: (.*)$/m.exec(text)?.[1] ?? name).trim()]))
writeFileSync(join(root, 'src', 'canvas-guide.ts'), `// Generated by scripts/embed-canvas-guide.mjs from canvas-guide/*.md. Edit those files, then run the script.
/** The Canvas design guide (Canvas's equivalent of Figma's figma-use and figma-generate-design skills), one entry per topic. */
export const CANVAS_GUIDE_TOPICS: Readonly<Record<string, string>> = ${JSON.stringify(topics, null, 1)};
/** One line per topic, for listings. */
export const CANVAS_GUIDE_TITLES: Readonly<Record<string, string>> = ${JSON.stringify(titles, null, 1)};
`)
console.log(`canvas-guide.ts: ${Object.keys(topics).length} topics, ${Object.values(topics).reduce((n, t) => n + t.length, 0)} characters`)
